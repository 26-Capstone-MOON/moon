"""STEP 5: Guidance generator — Korean guidance text per DP.

Generates Guidance (primary + pre_alert + action) per DP using a
conversational tone. Distance-in-meters phrasing is avoided in fallbacks
("곧" / "조금만 더 가면" instead of "50m 앞").

VIRTUAL DPs are normally generated by midpoint_service; the VIRTUAL
template here is kept for unit tests and edge-case callers.
"""

from __future__ import annotations

from dataclasses import dataclass

from constants import (
    FACILITY_KOREAN_NAMES,
    FACILITY_TURN_TYPES,
    TURN_TYPE_TO_ACTION,
)
from schemas import DecisionPoint, Guidance
from scoring_service import ScoredPoi

# ---------------------------------------------------------------------------
# Position text mapping
# ---------------------------------------------------------------------------

POSITION_TEXT: dict[str, str] = {
    "LEFT": "왼쪽에",
    "RIGHT": "오른쪽에",
    "FRONT": "전방에",
}

# ---------------------------------------------------------------------------
# Action text mapping (GuidanceAction → Korean)
# ---------------------------------------------------------------------------

ACTION_TEXT: dict[str, str] = {
    "LEFT_TURN": "좌회전",
    "RIGHT_TURN": "우회전",
    "U_TURN": "유턴",
    "CROSSWALK": "횡단보도",
    "STAIRS_UP": "올라가세요",
    "STAIRS_DOWN": "내려가세요",
    "OVERPASS": "건너세요",
    "UNDERPASS": "내려가세요",
    "ELEVATOR": "이용하세요",
}

# Direction-only text for pre_alert / no-landmark fallbacks
DIRECTION_TEXT: dict[str, str] = {
    "LEFT_TURN": "왼쪽",
    "RIGHT_TURN": "오른쪽",
    "U_TURN": "뒤쪽",
}

# ---------------------------------------------------------------------------
# Facility text (turnType → action verb only, no facility prefix)
# ---------------------------------------------------------------------------

# Action verb only — facility name is prepended dynamically in templates.
FACILITY_ACTION_VERB: dict[int, str] = {
    125: "건너세요",
    126: "내려가세요",
    127: "올라가세요",
    128: "내려가세요",
    129: "올라가세요",
    218: "이용하세요",
}

# ---------------------------------------------------------------------------
# Korean particle helper (조사 처리)
# ---------------------------------------------------------------------------


def _has_batchim(char: str) -> bool:
    """Check if a Korean character has a final consonant (받침).

    Args:
        char: single character to check.

    Returns:
        True if the character has batchim, False otherwise.
        Non-Korean characters are treated as no batchim.
    """
    if not ("가" <= char <= "힣"):
        return False
    return (ord(char) - 0xAC00) % 28 != 0


def _particle(name: str, with_batchim: str, without_batchim: str) -> str:
    """Append the correct Korean particle to a name.

    Args:
        name: the noun to attach the particle to.
        with_batchim: particle form when last char has batchim.
        without_batchim: particle form when last char has no batchim.

    Returns:
        name + appropriate particle.
    """
    if not name:
        return name
    last_char = name.rstrip()[-1]
    particle = with_batchim if _has_batchim(last_char) else without_batchim
    return f"{name}{particle}"


